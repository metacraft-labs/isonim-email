#!/usr/bin/env node
// build-tailwind.mjs — this repo's Tailwind class map.
//
// Produces build/tailwind.css and build/tailwind-styles.json (the map every
// `nim c`/`nim js` compile reads through -d:tailwindStylesPathOverride) from
// THIS repository's content only:
//
//   * the input stylesheet is generated here, under build/tailwind-extract/:
//     `@import "tailwindcss" source(none);` turns Tailwind's automatic
//     source detection off, and explicit `@source` globs name the content
//     (src/, examples/ and tests/ — templates live in all three). Nothing
//     outside this checkout is scanned;
//   * every output lands inside this repo's build/ directory;
//   * the Tailwind CLI is the dev shell's standalone `tailwindcss`, which
//     bundles the `tailwindcss` stylesheet, so no node_modules is needed
//     and nothing is installed anywhere.
//
// The parsing into the class map is isonim's extractor
// (../isonim/tools/tailwind-extract.mjs, or $ISONIM_DIR/tools/…), run in
// place and read-only: it is handed `--input` (so it does not generate an
// input file inside its own checkout) and an absolute `--out-dir`. It runs
// the CLI as `npx tailwindcss …` with the isonim checkout as its working
// directory; `npx` would resolve that checkout's node_modules or reach for
// the network, so a two-line `npx` shim, generated under
// build/tailwind-extract/bin/ and put first on PATH for the extractor
// only, forwards exactly `npx tailwindcss …` to the dev shell's binary and
// refuses anything else.
//
// `--variants sm,dark,hover,md` keeps variant classes under their full
// names with a `variant` field and records stripped units. `md` is listed
// only so an md: class is tagged rather than flattened, which lets the
// style pass reject it under the one-breakpoint rule.
//
// Safe to run while other processes read the outputs (the test recipes
// run concurrently, and a test may run this script while other test
// files compile against the map): the extractor writes into a staging
// directory private to this process, and each output replaces the
// published file by an atomic rename, only when its bytes changed. A
// reader therefore sees the old file or the new one, never a partial
// write, and an unchanged map is not rewritten at all. The generated
// input stylesheet and npx shim are published the same way.

import { spawnSync } from "node:child_process";
import {
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { delimiter, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const outDir = join(repoRoot, "build");
const workDir = join(outDir, "tailwind-extract");
const shimDir = join(workDir, "bin");

// The content globs, relative to the repo root. Exported for the tests.
export const contentGlobs = [
  "src/**/*.nim",
  "examples/**/*.nim",
  "tests/**/*.nim",
];

function findOnPath(exe) {
  for (const dir of (process.env.PATH || "").split(delimiter)) {
    if (dir.length === 0 || resolve(dir) === resolve(shimDir)) continue;
    const candidate = join(dir, exe);
    if (existsSync(candidate)) return candidate;
  }
  return null;
}

// Publishes `bytes` at `path` unless it already holds exactly them: a
// sibling temporary file renamed over the target (atomic on one
// filesystem), so a concurrent reader never sees a truncated file.
function publish(path, bytes, mode) {
  if (existsSync(path) && readFileSync(path).equals(bytes)) return;
  const tmp = `${path}.tmp-${process.pid}`;
  writeFileSync(tmp, bytes);
  if (mode !== undefined) chmodSync(tmp, mode);
  renameSync(tmp, path);
}

function fail(msg) {
  console.error(`build-tailwind: ${msg}`);
  process.exit(1);
}

function main() {
  const isonimDir = process.env.ISONIM_DIR
    ? resolve(process.env.ISONIM_DIR)
    : resolve(repoRoot, "..", "isonim");
  const extractor = join(isonimDir, "tools", "tailwind-extract.mjs");
  if (!existsSync(extractor)) {
    fail(`isonim's extractor not found at ${extractor} (set ISONIM_DIR)`);
  }
  const tailwind = findOnPath("tailwindcss");
  if (tailwind === null) {
    fail(
      "no `tailwindcss` on PATH: run inside this repo's dev shell (nix develop)",
    );
  }

  mkdirSync(shimDir, { recursive: true });
  const inputCss = join(workDir, "input.css");
  const lines = ['@import "tailwindcss" source(none);'];
  for (const glob of contentGlobs) {
    lines.push(`@source "${join(repoRoot, glob)}";`);
  }
  publish(inputCss, Buffer.from(lines.join("\n") + "\n"));

  const npxShim = join(shimDir, "npx");
  publish(
    npxShim,
    Buffer.from(
      [
        "#!/bin/sh",
        "# Generated by tools/tailwind/build-tailwind.mjs: forwards the",
        "# extractor's `npx tailwindcss …` to the dev shell's CLI.",
        `[ "$1" = tailwindcss ] || { echo "npx shim: refusing '$*'" >&2; exit 1; }`,
        "shift",
        `exec ${JSON.stringify(tailwind)} "$@"`,
        "",
      ].join("\n"),
    ),
    0o755,
  );

  // The extractor's outputs go to this process's own staging directory
  // and are published from there (see the header).
  const stageDir = join(workDir, `stage-${process.pid}`);
  rmSync(stageDir, { recursive: true, force: true });
  mkdirSync(stageDir, { recursive: true });

  const res = spawnSync(
    process.execPath,
    [
      extractor,
      "--input",
      inputCss,
      "--out-dir",
      stageDir,
      "--variants",
      "sm,dark,hover,md",
    ],
    {
      cwd: repoRoot,
      stdio: "inherit",
      env: {
        ...process.env,
        PATH: shimDir + delimiter + (process.env.PATH || ""),
      },
    },
  );
  if (res.error) {
    rmSync(stageDir, { recursive: true, force: true });
    fail(res.error.message);
  }
  if (res.status === 0)
    for (const name of ["tailwind.css", "tailwind-styles.json"])
      publish(join(outDir, name), readFileSync(join(stageDir, name)));
  rmSync(stageDir, { recursive: true, force: true });
  process.exit(res.status ?? 1);
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main();
}
